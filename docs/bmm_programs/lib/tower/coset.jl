#############################################################################
##
##  coset.jl — the coset table of H(W) over H(P), and how it is filled
##
##  W is a finite complex reflection group given by permutations (Chevie),
##  P = <generators subset> and N = |W : P|.  A coset tree is a list of
##  positive words x_1 = (), x_2, ..., x_N, closed under prefixes, whose
##  images represent the right cosets P x.  The table holds, for every
##  generator s of W and coset n, the row
##
##        x_n T_s = Σ_k h_nk x_k,        h_nk in H(P)  (on the left),
##
##  or nothing while it is unknown.  Further letters ngens+1, ngens+2, ..., each defined by a word in the
##  generators (extra[i]): their rows x_n T_l are kept like those of a generator, T_l^-1 is the inverse word.
##  The first, z, may occur in the tree; a letter marked pcomm commutes with P, and the cosets of the words in
##  such letters (1, z, z^2, ...) satisfy x T_s = T_s x for s in P.
##  The rows are filled by the setRow procedure of bmm.pdf §3.3 (setrow.jl, which adds the columns of the
##  inverse letters, T.invrows); this file has the table, its rows and columns as elements of H(P)^N, the
##  tests of a complete table, and the completed level as the flat algebra H(P) of the level above.
##  Part of the module Tower (twostep.jl); the letters of a level are printed
##  with the names of the group file (wordstr(T, w)).
##
#############################################################################

include("alg.jl")

# ---- the group ---------------------------------------------------------------------------------------------
struct Grp
    name::String
    gens::Vector                            # Chevie permutations, the generators s_1, ..., s_n of W
end
ngens(W::Grp) = length(W.gens)
# the function p -> the images of 1..deg under p, a name of the permutation p
function images(W::Grp)
    deg = maximum(length(g.d) for g in W.gens)
    p -> Int16[i^p for i in 1:deg]
end
# the permutation of a word w
product(W::Grp, w) = isempty(w) ? one(W.gens[1]) : prod(l > 0 ? W.gens[l] : inv(W.gens[-l]) for l in w)
# the elements of the subgroup generated by gens
function closure(W::Grp, gens)
    img = images(W); elts = [one(W.gens[1])]; seen = Set([img(elts[1])]); i = 0
    while i < length(elts)
        i += 1
        for g in gens
            p = elts[i] * g; k = img(p)
            k in seen || (push!(seen, k); push!(elts, p))
        end
    end
    elts
end

# The cosets P x of P = <gens[subset]>: a canonical name of P g is the smallest image vector of h g, h in P.
struct Cosets
    W::Grp
    subset::Vector{Int}
    P::Vector                               # the elements of P
    key::Function
end
function Cosets(W::Grp, subset)
    P = closure(W, W.gens[subset]); img = images(W)
    Cosets(W, subset, P, g -> minimum(img(h * g) for h in P))
end
# a breadth-first tree: for n = 1, 2, ... and s in order, the coset of x_n s is new -> next word x_n s;
# seeds: words that must be in the tree with all their prefixes (their cosets are reached through them only)
function bfs_tree(C::Cosets, order; seeds = Vector{Int}[])
    W = C.W; seeded = Dict{Vector{Int16},Vector{Int}}()
    for w in seeds, i in 1:length(w)
        k = C.key(product(W, w[1:i]))
        get!(seeded, k, w[1:i]) == w[1:i] || error("the prefixes $(seeded[k]) and $(w[1:i]) of the seeds lie in the same coset")
    end
    reps = [one(W.gens[1])]; words = [Int[]]; index = Dict(C.key(reps[1]) => 1); i = 0
    while i < length(words)
        i += 1
        for s in order
            g = reps[i] * W.gens[s]; k = C.key(g); haskey(index, k) && continue
            w = vcat(words[i], s)
            (haskey(seeded, k) && seeded[k] != w) && continue
            push!(reps, g); push!(words, w); index[k] = length(words)
        end
    end
    words
end
# the action of the generators on the cosets of a tree: act[n, s] = the index of P x_n s (error if the words
# are not prefix-closed, or two lie in the same coset, or a coset is missed)
function coset_action(C::Cosets, words; perms = C.W.gens, order::Int = 0)   # order: |W| if known (G34: 39191040 elements are not listed)
    W = C.W; index = Dict{Vector{Int16},Int}(); reps = Vector{Any}(undef, length(words))
    prodw(w) = isempty(w) ? one(perms[1]) : prod(perms[l] for l in w)
    isempty(words[1]) || error("the first word must be empty")
    at = Dict(Int[] => 1)
    for (n, w) in enumerate(words)
        n == 1 || haskey(at, w[1:end-1]) || error("the tree is not closed under prefixes: $w")
        at[w] = n; reps[n] = prodw(w); k = C.key(reps[n])
        haskey(index, k) && error("the words $(words[index[k]]) and $w lie in the same coset")
        index[k] = n
    end
    total = order > 0 ? order : length(closure(W, W.gens))
    length(words) * length(C.P) == total || error("the tree has $(length(words)) words; the index of P is $(total ÷ length(C.P))")
    act = zeros(Int, length(words), length(perms))
    for n in eachindex(words), s in eachindex(perms)
        act[n, s] = index[C.key(reps[n] * perms[s])]
    end
    act
end
# a breadth-first tree for an ordering of letters given by permutations (perms[l] for the letter l; e.g. the
# generators and a central element z as the letter ngens+1)
function bfs_letters(C::Cosets, order, perms)
    reps = [one(perms[1])]; words = [Int[]]; index = Dict(C.key(reps[1]) => 1); i = 0
    while i < length(words)
        i += 1
        for s in order
            g = reps[i] * perms[s]; k = C.key(g); haskey(index, k) && continue
            push!(reps, g); push!(words, vcat(words[i], s)); index[k] = length(words)
        end
    end
    words
end

# ---- the table ---------------------------------------------------------------------------------------------
const Row{S} = Vector{Tuple{Int32,SV{S}}}                # Σ h_k x_k, sorted by coset, h_k nonzero
mutable struct Table{S}
    name::String
    glob::Vector{Int}                       # glob[l] = the letter of the group file that the letter l of this level is
    A::FlatAlg{S}                           # H(P)
    q::Hecke{S}
    N::Int
    ngens::Int                              # the generators 1..ngens
    nletters::Int                           # ngens + the number of defined letters
    extra::Vector{Vector{Int}}              # the words (in the generators) of the letters ngens+1, ngens+2, ...
    pcomm::Vector{Bool}                     # pcomm[i]: the letter ngens+i commutes with P
    subset::Vector{Int}
    pindex::Vector{Int}                     # pindex[s] = j if s = subset[j], 0 otherwise
    words::Vector{Vector{Int}}
    parent::Vector{Int}
    letter::Vector{Int}
    children::Vector{Vector{Int}}
    act::Matrix{Int}
    rows::Vector{Vector{Union{Nothing,Row{S}}}}
    invrows::Vector{Vector{Union{Nothing,Row{S}}}}   # x_n T_s^-1, computed on demand once the rows of s are complete
    lists::Vector{Vector{SV{S}}}            # accumulator over the cosets
    touched::Vector{Int32}
end
# the empty table of H(W) over A = H(P) on the tree `words`, act the action of the letters on the cosets
function Table(name, A::FlatAlg{S}, ngens::Int, subset::Vector{Int}, words::Vector{Vector{Int}}, act::Matrix{Int};
               zword = Int[], extra = isempty(zword) ? Vector{Int}[] : [zword], pcomm = fill(true, length(extra)),
               glob = collect(1:ngens)) where {S}
    N = length(words); index = Dict(w => n for (n, w) in enumerate(words)); nl = ngens + length(extra)
    parent = [n == 1 ? 0 : index[words[n][1:end-1]] for n in 1:N]
    letter = [n == 1 ? 0 : words[n][end] for n in 1:N]
    children = [Int[] for _ in 1:N]; for n in 2:N; push!(children[parent[n]], n); end
    pindex = zeros(Int, ngens); for (j, s) in enumerate(subset); pindex[s] = j; end
    Table{S}(name, glob, A, A.q, N, ngens, nl, extra, pcomm, subset, pindex, words, parent, letter, children, act,
             [Vector{Union{Nothing,Row{S}}}(nothing, N) for _ in 1:nl], [Vector{Union{Nothing,Row{S}}}(nothing, N) for _ in 1:nl],
             [SV{S}[] for _ in 1:N], Int32[])
end
Base.show(io::IO, T::Table) = print(io, T.name)
# a word of the level in the letters of the group file (LETTERS, set by the driver): s1 s4 s1, s2², 1 for the
# empty word; a letter beyond the generators is a defined letter (z)
const LETTERS = String[]
function wordstr(T::Table, w)
    isempty(w) && return "1"
    name(l) = abs(l) <= T.ngens ? (isempty(LETTERS) ? "s$(T.glob[abs(l)])" : LETTERS[T.glob[abs(l)]]) : "z"
    parts = String[]; i = 1
    while i <= length(w)
        j = i; while j < length(w) && w[j+1] == w[i]; j += 1; end
        push!(parts, name(w[i]) * sup(sign(w[i]) * (j - i + 1))); i = j + 1
    end
    join(parts, " ")
end
# the Hecke relation of the letter s, over R' (r_0 = 1): T_s² = e1 T_s + 1, T_s³ = c2 T_s² + c1 T_s + 1
function heckestr(T::Table, s::Int)
    k = T.q.k; Ts = "T_" * wordstr(T, [s])
    "$Ts$(sup(k)) = " * join([j == 0 ? "1" : "$(RNAMES[j]) $Ts$(sup(j))" for j in k-1:-1:0], " + ")
end
isz(T::Table, s) = s > T.ngens                                   # a defined letter
xword(T::Table, s) = T.extra[s - T.ngens]                       # its word
xinv(T::Table, s) = -reverse(xword(T, s))                       # the word of its inverse
# the cosets whose words consist of letters commuting with P (1, z, z^2, ...): there x T_s = T_s x for s in P
zpowers(T::Table) = [n for n in 1:T.N if all(l -> isz(T, l) && T.pcomm[l - T.ngens], T.words[n])]
isopen(T::Table, n, s) = T.rows[s][n] === nothing
nopen(T::Table) = sum(count(isnothing, r) for r in T.rows)
complete(T::Table) = nopen(T) == 0
erow(::Type{S}, n::Integer) where {S} = Row{S}([(Int32(n), svunit(S, 1))])      # the row of x_n itself
# the coset of x_n under a letter (negative: the inverse generator)
cosetof(T::Table, n::Int, l::Int) = l > 0 ? T.act[n, l] : findfirst(==(n), view(T.act, :, -l))
Pword(T::Table, w) = T.subset[w]                           # a word in the generators of P as a word in W
Tgen(T::Table, s::Int) = element(T.A, [T.pindex[s]])      # T_s, s in P, as an element of H(P)

# accumulation of rows: Σ (h_k x_k) with the sums in H(P) formed once per coset
@inline function radd!(T::Table{S}, m::Integer, h::SV{S}) where {S}
    isempty(T.lists[m]) && push!(T.touched, m)
    push!(T.lists[m], h)
end
function rcollect!(T::Table{S}) where {S}
    sort!(T.touched); out = Row{S}()
    for m in T.touched
        l = T.lists[m]; h = length(l) == 1 ? l[1] : addall(T.A, ((one(S), x) for x in l))
        empty!(l); iszero(h) || push!(out, (m, h))
    end
    empty!(T.touched); out
end
# v T_s; nothing if a row is missing
function row_gen(T::Table{S}, v::Row{S}, s::Int) where {S}
    rows = T.rows[s]
    for (k, _) in v; rows[k] === nothing && return nothing; end
    for (k, h) in v, (m, g) in rows[k]; radd!(T, m, mul(T.A, h, g)); end
    rcollect!(T)
end
# c v, c in the ground ring
function rscale(v::Row{S}, c::S) where {S}
    isone(c) && return v
    out = Row{S}()
    for (k, h) in v; g = scale(c, h); iszero(g) || push!(out, (k, g)); end
    out
end
function rsub(v::Row{S}, w::Row{S}) where {S}                # v - w
    out = Row{S}(); i = 1; j = 1
    while i <= length(v) || j <= length(w)
        if j > length(w) || (i <= length(v) && v[i][1] < w[j][1])
            push!(out, v[i]); i += 1
        elseif i > length(v) || w[j][1] < v[i][1]
            push!(out, (w[j][1], -w[j][2])); j += 1
        else
            h = v[i][2] - w[j][2]; iszero(h) || push!(out, (v[i][1], h)); i += 1; j += 1
        end
    end
    out
end
radd(v::Row, w::Row) = rsub(v, rscale(w, -1 * one(eltype(w[1][2].val))))      # v + w
# v T_s^-1 = v T_s^(k-1) - r_(k-1) v T_s^(k-2) - ... - r_1 v   (Horner)
function row_inv_horner(T::Table{S}, v::Row{S}, s::Int) where {S}
    r = T.q.r; img = v
    for j in length(r)-1:-1:1
        img = row_gen(T, img, s); img === nothing && return nothing
        img = rsub(img, rscale(v, r[j+1]))
    end
    img
end
# the row x_n T_s^-1, cached once all rows of s are known
function invrow(T::Table{S}, n::Int, s::Int) where {S}
    T.invrows[s][n] === nothing || return T.invrows[s][n]
    any(isnothing, T.rows[s]) && return nothing
    T.invrows[s][n] = row_inv_horner(T, erow(S, n), s)
end
# v T_s^-1
function row_inv(T::Table{S}, v::Row{S}, s::Int) where {S}
    isz(T, s) && return row_word(T, v, xinv(T, s))              # T_l^-1 = T_(its word)^-1
    any(isnothing, T.rows[s]) && return row_inv_horner(T, v, s)
    for (k, _) in v; invrow(T, Int(k), s); end               # before accumulating: invrow uses the accumulator itself
    for (k, h) in v, (m, g) in T.invrows[s][k]; radd!(T, m, mul(T.A, h, g)); end
    rcollect!(T)
end
# v T_l for a letter l, v T_w for a word w
row_letter(T::Table, v::Row, l::Int) = l > 0 ? row_gen(T, v, l) : row_inv(T, v, -l)
function row_word(T::Table, v::Row, w)
    for l in w; v = row_letter(T, v, l); v === nothing && return nothing; end
    v
end
coords(T::Table{S}, w) where {S} = row_word(T, erow(S, 1), w)     # the coordinates of T_w: e_1 under w
# the coefficient h_m of x_m in v
function rcoef(v::Row{S}, m::Integer) where {S}
    k = searchsortedfirst(v, (Int32(m), svzero(S)); by = first)
    (k <= length(v) && v[k][1] == m) ? v[k][2] : svzero(S)
end
# (v)·c for c in H(P) from the left:  Σ (c h_k) x_k
function lscale(T::Table{S}, c::SV{S}, v::Row{S}) where {S}
    out = Row{S}()
    for (k, h) in v; g = mul(T.A, c, h); iszero(g) || push!(out, (k, g)); end
    out
end

# ---- columns: a column ψ in H(P)^N is the left-linear form Σ p_n x_n -> Σ p_n ψ_n; M_s ψ is h -> ψ(h T_s) -------
const Col{S} = Vector{Union{Nothing,SV{S}}}
colzero(::Type{S}, N) where {S} = Col{S}(nothing, N)
# the column with the entry h (default 1) at the coset c
function colunit(::Type{S}, N, c, h = one(S)) where {S}
    ψ = colzero(S, N)
    ψ[c] = h isa SV ? h : svunit(S, 1)
    ψ
end
# M_s ψ: h -> ψ(h T_s) (rows: those of T_s, or of T_s^-1)
function col_gen(T::Table{S}, ψ::Col{S}, s::Int; rows = T.rows[s]) where {S}
    out = colzero(S, T.N)
    for n in 1:T.N
        r = rows[n]; r === nothing && error("col_gen: an open row")
        terms = [(one(S), mul(T.A, h, ψ[k])) for (k, h) in r if ψ[k] !== nothing]
        isempty(terms) && continue
        v = length(terms) == 1 ? terms[1][2] : addall(T.A, terms)
        iszero(v) || (out[n] = v)
    end
    out
end
function col_sub(u::Col{S}, c::S, v::Col{S}) where {S}      # u - c v
    out = colzero(S, length(u))
    for n in eachindex(u)
        w = v[n] === nothing ? u[n] : u[n] === nothing ? -scale(c, v[n]) : u[n] - scale(c, v[n])
        (w === nothing || iszero(w)) || (out[n] = w)
    end
    out
end
# M_(s^-1) ψ: h -> ψ(h T_s^-1)
function col_inv(T::Table{S}, ψ::Col{S}, s::Int) where {S}
    isz(T, s) && return col_word(T, ψ, xinv(T, s))
    if !any(isnothing, T.rows[s])                          # through the rows of T_s^-1
        for n in 1:T.N; invrow(T, n, s); end
        return col_gen(T, ψ, s; rows = T.invrows[s])
    end
    r = T.q.r; out = ψ
    for j in length(r)-1:-1:1; out = col_sub(col_gen(T, out, s), r[j+1], ψ); end
    out
end
col_letter(T::Table, ψ::Col, l::Int) = l > 0 ? col_gen(T, ψ, l) : col_inv(T, ψ, -l)       # M_l ψ for a letter l
col_word(T::Table, ψ::Col, w) = foldr((l, c) -> col_letter(T, c, l), w; init = ψ)       # M_w ψ: the letters from the right
support(ψ::Col) = findall(!isnothing, ψ)                                            # the cosets where ψ ≠ 0
# the value ψ(v) = Σ_n v_n ψ_n in H(P) of a form on a row, and E(v) = v_1
function colval(T::Table{S}, v::Row{S}, ψ::Col{S}) where {S}
    terms = [(one(S), mul(T.A, h, ψ[k])) for (k, h) in v if ψ[k] !== nothing]
    isempty(terms) ? zero(T.A) : addall(T.A, terms)
end

# ---- the tests of a complete table: (R) ----------------------------------------------------------------------
function test_hecke(T::Table{S}, s::Int) where {S}      # M_s^k = Σ r_j M_s^j on every e_n
    k = T.q.k; r = T.q.r
    for n in 1:T.N
        v = [erow(S, n)]; for j in 1:k; push!(v, row_gen(T, v[end], s)); end
        c = v[1]; for j in 2:k; c = radd(c, rscale(v[j], r[j])); end
        v[k+1] == c || return false
    end
    true
end
# on every coset: the relation rel = (l, r); the rows of the rule one; the tree rows
test_relation(T::Table{S}, rel) where {S} = all(row_word(T, erow(S, n), rel[1]) == row_word(T, erow(S, n), rel[2]) for n in 1:T.N)
test_one(T::Table{S}) where {S} = all(T.rows[s][n] == Row{S}([(Int32(n), Tgen(T, s))]) for s in T.subset for n in zpowers(T))
test_tree(T::Table{S}) where {S} = all(T.rows[T.letter[m]][T.parent[m]] == erow(S, m) for m in 2:T.N)
# the stage Relations of H: the tree and one rows, the Hecke relations, the relations, the defined letters
test_R(T::Table, relations) = for j in 1:test_R_count(T.ngens, T.nletters, length(relations)); test_R_piece(T, relations, j); end
# test_R in pieces, one line of the record each (the driver can write a checkpoint between two pieces): the tree rows,
# a line on the defined letters (if there are several), the Hecke relation of each generator, each relation, the
# matrix of each defined letter
test_R_count(ngens::Int, nletters::Int, nrel::Int) = 1 + (nletters > ngens + 1 ? 1 : 0) + ngens + nrel + (nletters - ngens)
function test_R_piece(T::Table, relations, j::Int)
    j == 1 && return testing("the tree rows x_n T_s = x_m (x_m = x_n s) and x T_s = T_s x (s in P, x = 1" * (T.nletters > T.ngens ? ", z, z^2, ..." : "") * ") are in the table", test_tree(T) && test_one(T))
    j -= 1
    if T.nletters > T.ngens + 1
        j == 1 && return say("the letters $(T.ngens + 2)..$(T.nletters) only help the enumeration; their matrices are tested against their words")
        j -= 1
    end
    j <= T.ngens && return testing("$(heckestr(T, j)) on all cosets", test_hecke(T, j))
    j -= T.ngens
    if j <= length(relations)
        rel = relations[j]
        return testing("$(wordstr(T, rel[1])) = $(wordstr(T, rel[2])) on all cosets", test_relation(T, rel))
    end
    l = T.ngens + j - length(relations)
    l <= T.nletters || error("test_R_piece: no piece $(j + length(relations))")
    testing("the matrix of the letter $l is that of its word $(wordstr(T, xword(T, l))) on all cosets", test_relation(T, ([l], xword(T, l))))
end
# the size of the table: rows, cosets per row, terms per entry
function statistics(T::Table)
    rows = [r for m in T.rows for r in m if r !== nothing]; supp = length.(rows)
    terms = [nterms(h) for r in rows for (_, h) in r]
    say("rows: $(length(rows)); cosets per row: mean $(round(sum(supp) / length(supp), digits = 2)), max $(maximum(supp)); " *
        "entries: $(sum(supp)); terms per entry: mean $(round(sum(terms) / length(terms), digits = 1)), max $(maximum(terms))")
end

# ---- the completed level as the flat algebra of the next level ------------------------------------------------
# basis b_i x_n (index (n-1) d + i), words: the word of b_i in W followed by x_n
function FlatAlg(T::Table{S}, name::String) where {S}
    complete(T) || error("the table is not complete")
    A = T.A; d = A.d; N = T.N; ng = T.ngens
    words = [vcat(Pword(T, A.words[i]), T.words[n]) for n in 1:N for i in 1:d]
    function flat(r::Row{S})                             # Σ h_k x_k as a vector on the basis b_i x_n
        idx = Int32[]; val = S[]
        for (k, h) in r, j in eachindex(h.idx); push!(idx, (k - 1) * d + h.idx[j]); push!(val, h.val[j]); end
        p = sortperm(idx)
        SV{S}(idx[p], val[p])
    end
    R = [[flat(lscale(T, basis(A, i), T.rows[s][n])) for n in 1:N for i in 1:d] for s in 1:ng]
    L = Vector{Vector{SV{S}}}(undef, ng)
    for s in 1:ng
        j = T.pindex[s]
        if j > 0                                         # T_s b_i x_n = (T_j b_i) x_n
            L[s] = [SV{S}(Int32[(n - 1) * d + x for x in A.L[j][i].idx], copy(A.L[j][i].val)) for n in 1:N for i in 1:d]
        else                                             # T_s b_i x_n through the rows: (x_1 T_s) b_i x_n
            L[s] = [flat(row_word(T, T.rows[s][1], vcat(Pword(T, A.words[i]), T.words[n]))) for n in 1:N for i in 1:d]
        end
    end
    FlatAlg(name, T.q, words, R, L; lower_d = d, cosetwords = T.words)
end
